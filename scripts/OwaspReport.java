import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Converts the JSON report of OWASP dependency-check into docs/OWASP_DC.md.
 * Run: java scripts/OwaspReport.java [report.json] [out.md]  (JDK 21 source launcher, no dependencies).
 */
public class OwaspReport {

    public static void main(String[] args) throws Exception {
        Path in = Path.of(args.length > 0 ? args[0] : "target/dependency-check-report.json");
        Path out = Path.of(args.length > 1 ? args[1] : "docs/OWASP_DC.md");
        if (!Files.exists(in)) {
            System.err.println("OwaspReport: no report at " + in + ", nothing written");
            return;
        }
        Object root = new Json(Files.readString(in, StandardCharsets.UTF_8)).value();
        String md = render(root);
        if (out.getParent() != null) Files.createDirectories(out.getParent());
        Files.writeString(out, md, StandardCharsets.UTF_8);
        System.out.println("OwaspReport: wrote " + out);
    }

    @SuppressWarnings("unchecked")
    static String render(Object root) {
        Map<String, Object> r = (Map<String, Object>) root;
        Map<String, Object> info = r.get("scanInfo") instanceof Map<?, ?> m ? (Map<String, Object>) m : Map.of();
        Map<String, Object> proj = r.get("projectInfo") instanceof Map<?, ?> m ? (Map<String, Object>) m : Map.of();
        List<Object> deps = r.get("dependencies") instanceof List<?> l ? (List<Object>) l : List.of();

        List<String[]> rows = new ArrayList<>(); // score, id, severity, dependency, description
        int vulnerable = 0;
        for (Object d : deps) {
            Map<String, Object> dep = (Map<String, Object>) d;
            List<Object> vulns = dep.get("vulnerabilities") instanceof List<?> l ? (List<Object>) l : List.of();
            if (!vulns.isEmpty()) vulnerable++;
            for (Object v : vulns) {
                Map<String, Object> vu = (Map<String, Object>) v;
                rows.add(new String[]{score(vu), str(vu.get("name")), str(vu.get("severity")),
                        str(dep.get("fileName")), str(vu.get("description"))});
            }
        }
        rows.sort(Comparator.comparingDouble((String[] x) -> Double.parseDouble(x[0])).reversed()
                .thenComparing(x -> x[1]));

        StringBuilder sb = new StringBuilder();
        sb.append("# OWASP dependency-check\n\n");
        sb.append("Generated by `mvn -Powasp verify` (see CONTRIBUTING.md). Do not edit.\n\n");
        sb.append("- Project: ").append(esc(str(proj.get("name")))).append("\n");
        sb.append("- Report date: ").append(esc(str(proj.get("reportDate")))).append("\n");
        sb.append("- Engine version: ").append(esc(str(info.get("engineVersion")))).append("\n");
        sb.append("- Dependencies scanned: ").append(deps.size()).append("\n");
        sb.append("- Vulnerable dependencies: ").append(vulnerable).append("\n");
        sb.append("- Vulnerabilities: ").append(rows.size()).append("\n\n");
        if (rows.isEmpty()) {
            sb.append("No known vulnerabilities.\n");
            return sb.toString();
        }
        sb.append("| CVSS | Severity | Id | Dependency | Description |\n|---|---|---|---|---|\n");
        for (String[] x : rows) {
            sb.append("| ").append(x[0]).append(" | ").append(esc(x[2])).append(" | ").append(esc(x[1]))
                    .append(" | ").append(esc(x[3])).append(" | ").append(esc(shorten(x[4]))).append(" |\n");
        }
        return sb.toString();
    }

    /** Highest base score among cvssv2 (score), cvssv3 and cvssv4 (baseScore). */
    @SuppressWarnings("unchecked")
    private static String score(Map<String, Object> v) {
        double best = 0;
        for (String k : new String[]{"cvssv2", "cvssv3", "cvssv4"}) {
            if (!(v.get(k) instanceof Map<?, ?> m)) continue;
            Map<String, Object> cv = (Map<String, Object>) m;
            Object n = cv.get("baseScore") != null ? cv.get("baseScore") : cv.get("score");
            if (n instanceof Number num) best = Math.max(best, num.doubleValue());
        }
        return Double.toString(best);
    }

    private static String str(Object o) {
        return o == null ? "" : o.toString();
    }

    private static String shorten(String s) {
        s = s.replaceAll("\\s+", " ").strip();
        return s.length() > 240 ? s.substring(0, 237) + "..." : s;
    }

    private static String esc(String s) {
        return s.replace("|", "\\|").replace("\r", " ").replace("\n", " ");
    }

    /** Minimal JSON parser: objects as Map, arrays as List, numbers as Double, plus String, Boolean, null. */
    static final class Json {
        private static final Pattern NUMBER = Pattern.compile("-?\\d+(\\.\\d+)?([eE][+-]?\\d+)?");
        private final String s;
        private int i;

        Json(String s) {
            this.s = s;
        }

        Object value() {
            Object v = read();
            ws();
            if (i != s.length()) throw new IllegalArgumentException("trailing data at " + i);
            return v;
        }

        private Object read() {
            ws();
            char c = s.charAt(i);
            if (c == '{') {
                i++;
                Map<String, Object> m = new LinkedHashMap<>();
                ws();
                if (s.charAt(i) == '}') {
                    i++;
                    return m;
                }
                while (true) {
                    ws();
                    String k = string();
                    ws();
                    expect(':');
                    m.put(k, read());
                    ws();
                    if (s.charAt(i) == ',') {
                        i++;
                        continue;
                    }
                    expect('}');
                    return m;
                }
            }
            if (c == '[') {
                i++;
                List<Object> l = new ArrayList<>();
                ws();
                if (s.charAt(i) == ']') {
                    i++;
                    return l;
                }
                while (true) {
                    l.add(read());
                    ws();
                    if (s.charAt(i) == ',') {
                        i++;
                        continue;
                    }
                    expect(']');
                    return l;
                }
            }
            if (c == '"') return string();
            if (s.startsWith("true", i)) {
                i += 4;
                return Boolean.TRUE;
            }
            if (s.startsWith("false", i)) {
                i += 5;
                return Boolean.FALSE;
            }
            if (s.startsWith("null", i)) {
                i += 4;
                return null;
            }
            Matcher m = NUMBER.matcher(s).region(i, s.length());
            if (!m.lookingAt()) throw new IllegalArgumentException("bad json at " + i);
            i = m.end();
            return Double.parseDouble(m.group());
        }

        private String string() {
            expect('"');
            StringBuilder b = new StringBuilder();
            while (true) {
                char c = s.charAt(i++);
                if (c == '"') return b.toString();
                if (c != '\\') {
                    b.append(c);
                    continue;
                }
                char e = s.charAt(i++);
                switch (e) {
                    case 'n' -> b.append('\n');
                    case 't' -> b.append('\t');
                    case 'r' -> b.append('\r');
                    case 'b' -> b.append('\b');
                    case 'f' -> b.append('\f');
                    case 'u' -> {
                        b.append((char) Integer.parseInt(s.substring(i, i + 4), 16));
                        i += 4;
                    }
                    default -> b.append(e);
                }
            }
        }

        private void expect(char c) {
            if (s.charAt(i) != c) throw new IllegalArgumentException("expected " + c + " at " + i);
            i++;
        }

        private void ws() {
            while (i < s.length() && Character.isWhitespace(s.charAt(i))) i++;
        }
    }
}
